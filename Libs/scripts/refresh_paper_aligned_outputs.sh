#!/bin/bash
set -euo pipefail

echo "This historical paper-asset refresh is disabled. Canonical evidence is validated from Output/canonical manifests and table_cell_registry.json; no manuscript assets are generated by this repository path." >&2
exit 64

source /share/home/hwxu/Researches/D2Plus/Libs/scripts/slurm_common.sh

log() {
  printf '[%s] %s\n' "$(date '+%F %T')" "$*"
}

EXP_CFG_DEFAULT="${EXP_CFG:-Libs/configs/exp_paper_ready.yaml}"
CONDA_ENV="${CONDA_ENV_OVERRIDE:-$(profile_get "${EXP_CFG_DEFAULT}" "explain_summary" "conda_env" "hw")}"

activate_conda_env "${CONDA_ENV}"
cd /share/home/hwxu/Researches/D2Plus

LOG_DIR=$(python3 - "${EXP_CFG_DEFAULT}" <<'PY'
import sys
import yaml

cfg = yaml.safe_load(open(sys.argv[1], "r", encoding="utf-8"))
outputs = cfg.get("outputs", {}) if isinstance(cfg.get("outputs", {}), dict) else {}
print(outputs.get("log_dir", "Output/logs/paper_aligned"))
PY
)
mkdir -p "${LOG_DIR}"
record_env_snapshot "${LOG_DIR}" "${SLURM_JOB_NAME:-DPlus_refresh_paper_outputs}"

log_run_header "refresh paper-aligned aggregates, significance rows, generated tables, and PDFs"

SEEDS=$(python3 - "${EXP_CFG_DEFAULT}" <<'PY'
import sys
import yaml

cfg = yaml.safe_load(open(sys.argv[1], "r", encoding="utf-8"))
seeds = cfg.get("experiment", {}).get("seeds", [])
if len(seeds) == 0:
    raise ValueError("experiment.seeds is empty")
print(",".join(str(int(seed)) for seed in seeds))
PY
)

DATASETS=$(python3 - "${EXP_CFG_DEFAULT}" <<'PY'
import sys
import yaml

cfg = yaml.safe_load(open(sys.argv[1], "r", encoding="utf-8"))
multi = cfg.get("multi_run", {}) if isinstance(cfg.get("multi_run", {}), dict) else {}
datasets = multi.get("datasets", [])
if not isinstance(datasets, list) or len(datasets) == 0:
    dataset_cfg = cfg.get("dataset", {}) if isinstance(cfg.get("dataset", {}), dict) else {}
    datasets = [dataset_cfg.get("name", "")]
datasets = [str(dataset).strip() for dataset in datasets if str(dataset).strip()]
if len(datasets) == 0:
    raise ValueError("No datasets configured in multi_run.datasets or dataset.name")
print("\n".join(datasets))
PY
)

BASELINE_CONFIGS=$(python3 - "${EXP_CFG_DEFAULT}" <<'PY'
import sys
import yaml

cfg = yaml.safe_load(open(sys.argv[1], "r", encoding="utf-8"))
eval_cfg = cfg.get("evaluation", {}) if isinstance(cfg.get("evaluation", {}), dict) else {}
sig_cfg = eval_cfg.get("significance", {}) if isinstance(eval_cfg.get("significance", {}), dict) else {}
baseline_models = sig_cfg.get("baseline_models", [])
if not isinstance(baseline_models, list) or len(baseline_models) == 0:
    raise ValueError("evaluation.significance.baseline_models is empty")
print(",".join(f"Libs/configs/baselines/{str(model).lower()}.yaml" for model in baseline_models))
PY
)

log "Refreshing RumorDiffusion aggregate rows for seeds: ${SEEDS}"
python3 - "${EXP_CFG_DEFAULT}" <<'PY'
import os
import sys

from Libs.exp.run import read_yaml_like, refresh_result_aggregate_row

exp_cfg_path = sys.argv[1]
cfg = read_yaml_like(exp_cfg_path)
outputs = cfg.get("outputs", {}) if isinstance(cfg.get("outputs", {}), dict) else {}
results_dir = outputs.get("results_dir", os.path.join("Output", "results"))
multi = cfg.get("multi_run", {}) if isinstance(cfg.get("multi_run", {}), dict) else {}
datasets = multi.get("datasets", [])
if not isinstance(datasets, list) or len(datasets) == 0:
    dataset_cfg = cfg.get("dataset", {}) if isinstance(cfg.get("dataset", {}), dict) else {}
    datasets = [dataset_cfg.get("name", "")]
datasets = [str(dataset).strip() for dataset in datasets if str(dataset).strip()]
seeds = [int(seed) for seed in cfg.get("experiment", {}).get("seeds", [])]
eval_cfg = cfg.get("evaluation", {}) if isinstance(cfg.get("evaluation", {}), dict) else {}
sig_cfg = eval_cfg.get("significance", {}) if isinstance(eval_cfg.get("significance", {}), dict) else {}
reference_model = str(sig_cfg.get("reference_model", "rumordiffusion")).lower()
reference_model_cfg_path = f"Libs/configs/baselines/{reference_model}.yaml"

for dataset_name in datasets:
    refresh_result_aggregate_row(
        csv_path=os.path.join(results_dir, f"{dataset_name}.csv"),
        dataset_name=dataset_name,
        source_dataset_name=dataset_name,
        transfer_mode="main",
        model_name=reference_model,
        model_cfg_path=reference_model_cfg_path,
        exp_cfg_path=exp_cfg_path,
        seeds=seeds,
    )
    print(f"refreshed aggregate: {dataset_name}/{reference_model}")
PY

log "Refreshing paired-bootstrap significance rows"
while IFS= read -r DATASET_NAME; do
  [ -n "${DATASET_NAME}" ] || continue
  python3 -m Libs.exp.run \
    --exp "${EXP_CFG_DEFAULT}" \
    --model "${BASELINE_CONFIGS}" \
    --dataset_override "${DATASET_NAME}" \
    --source_dataset_override "${DATASET_NAME}" \
    --seeds "${SEEDS}" \
    --refresh_significance
done <<< "${DATASETS}"

log "Validating refreshed aggregate and significance artifacts"
python3 - "${EXP_CFG_DEFAULT}" <<'PY'
import csv
import os
import sys

from Libs.exp.run import read_yaml_like

exp_cfg_path = sys.argv[1]
cfg = read_yaml_like(exp_cfg_path)
outputs = cfg.get("outputs", {}) if isinstance(cfg.get("outputs", {}), dict) else {}
results_dir = outputs.get("results_dir", os.path.join("Output", "results"))
revision_csv = outputs.get("revision_artifacts_csv", os.path.join(results_dir, "revision_artifacts.csv"))
multi = cfg.get("multi_run", {}) if isinstance(cfg.get("multi_run", {}), dict) else {}
datasets = multi.get("datasets", [])
if not isinstance(datasets, list) or len(datasets) == 0:
    dataset_cfg = cfg.get("dataset", {}) if isinstance(cfg.get("dataset", {}), dict) else {}
    datasets = [dataset_cfg.get("name", "")]
datasets = [str(dataset).strip() for dataset in datasets if str(dataset).strip()]
seeds = {str(int(seed)) for seed in cfg.get("experiment", {}).get("seeds", [])}
eval_cfg = cfg.get("evaluation", {}) if isinstance(cfg.get("evaluation", {}), dict) else {}
sig_cfg = eval_cfg.get("significance", {}) if isinstance(eval_cfg.get("significance", {}), dict) else {}
reference_model = str(sig_cfg.get("reference_model", "rumordiffusion")).lower()
baseline_models = [str(model).lower() for model in sig_cfg.get("baseline_models", [])]
metrics = [str(metric) for metric in sig_cfg.get("metrics", [])]

for dataset_name in datasets:
    csv_path = os.path.join(results_dir, f"{dataset_name}.csv")
    with open(csv_path, "r", encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    unique_rows = {}
    for row in rows:
        key = (row.get("dataset", ""), row.get("source_dataset", ""), row.get("run_kind", ""), row.get("transfer_mode", ""), row.get("model", ""), row.get("model_cfg", ""), row.get("exp_cfg", ""), row.get("seed", ""))
        if key in unique_rows:
            raise RuntimeError(f"Duplicate result key {key}; timestamp conflict resolution is disabled")
        unique_rows[key] = row
    seed_rows = [
        row for row in unique_rows.values()
        if row.get("dataset", "") == dataset_name
        and row.get("source_dataset", "") == dataset_name
        and row.get("run_kind", "") == "main"
        and row.get("transfer_mode", "") == "main"
        and row.get("model", "") == reference_model
        and row.get("seed", "") in seeds
    ]
    observed_seeds = {row.get("seed", "") for row in seed_rows}
    if observed_seeds != seeds:
        raise RuntimeError(f"{dataset_name}: missing {reference_model} seeds {sorted(seeds - observed_seeds)}")
    agg_rows = [
        row for row in unique_rows.values()
        if row.get("dataset", "") == dataset_name
        and row.get("source_dataset", "") == dataset_name
        and row.get("run_kind", "") == "main"
        and row.get("transfer_mode", "") == "main"
        and row.get("model", "") == f"{reference_model}_agg"
        and row.get("seed", "") == "agg"
    ]
    if len(agg_rows) != 1:
        raise RuntimeError(f"{dataset_name}: expected one {reference_model}_agg row, found {len(agg_rows)}")

with open(revision_csv, "r", encoding="utf-8", newline="") as f:
    revision_rows = list(csv.DictReader(f))
for dataset_name in datasets:
    for baseline_model in baseline_models:
        for metric in metrics:
            for seed in seeds:
                matches = [
                    row for row in revision_rows
                    if row.get("dataset", "") == dataset_name
                    and row.get("source_dataset", "") == dataset_name
                    and row.get("run_kind", "") == "main"
                    and row.get("model", "") == reference_model
                    and row.get("compare_model", "") == baseline_model
                    and row.get("metric", "") == metric
                    and row.get("seed", "") == seed
                    and row.get("artifact_type", "") == "significance"
                ]
                if len(matches) == 0:
                    raise RuntimeError(f"{dataset_name}: missing significance {reference_model} vs {baseline_model} {metric} seed {seed}")
print("artifact gate passed")
PY

log "Generating paper tables and tradeoff figure"
python3 -m py_compile Libs/exp/run.py Libs/scripts/generate_paper_assets.py
python3 Libs/scripts/generate_paper_assets.py
mkdir -p Docs/rebuttal/responses/round1/Figs
cp Docs/paper/Figs/generated/rebuttal_tradeoff.pdf Docs/rebuttal/responses/round1/Figs/deployment_tradeoff.pdf

compile_pdf() {
  local doc_dir="$1"
  local tex_name="$2"
  local stem="${tex_name%.tex}"
  (
    cd "${doc_dir}"
    pdflatex -interaction=nonstopmode "${tex_name}"
    if [ -f "${stem}.aux" ] && rg -q "\\\\bibdata|\\\\citation" "${stem}.aux"; then
      bibtex "${stem}"
    fi
    pdflatex -interaction=nonstopmode "${tex_name}"
    pdflatex -interaction=nonstopmode "${tex_name}"
  )
}

log "Compiling revised manuscript and rebuttal PDFs"
compile_pdf Docs/paper main.tex
compile_pdf Docs/rebuttal/responses/round1 main.tex
compile_pdf Docs/rebuttal/responses/round1 summary_of_differences.tex

log "Scanning LaTeX logs"
if rg -n "undefined references|undefined citations|Citation .* undefined|Reference .* undefined|Fatal error|Emergency stop|Rerun to get cross-references" \
  Docs/paper/main.log \
  Docs/rebuttal/responses/round1/main.log \
  Docs/rebuttal/responses/round1/summary_of_differences.log; then
  exit 1
fi

log "Scanning reader-visible PDF text and source markers"
PDF_TEXT_DIR="${LOG_DIR}/pdf_text_${SLURM_JOB_ID:-local}"
mkdir -p "${PDF_TEXT_DIR}"
pdftotext Docs/paper/main.pdf "${PDF_TEXT_DIR}/paper_main.txt"
pdftotext Docs/rebuttal/responses/round1/main.pdf "${PDF_TEXT_DIR}/rebuttal_main.txt"
pdftotext Docs/rebuttal/responses/round1/summary_of_differences.pdf "${PDF_TEXT_DIR}/summary_of_differences.txt"
if rg -n -i "\\b(TBD|pending|internal|smoke)\\b|714577521992343552|673611867181473792" \
  "${PDF_TEXT_DIR}" \
  Docs/paper/Sections/Exp.tex \
  Docs/rebuttal/responses/round1/paper.tex \
  Docs/rebuttal/responses/round1/summary_of_differences.tex; then
  exit 1
fi
if rg -n "0\\.759|0\\.750|217\\.54|433\\.49|0\\.866|0\\.816|0\\.739\\$\\\\pm\\$0\\.032" \
  Docs/paper/Sections/Exp.tex \
  Docs/rebuttal/responses/round1/paper.tex; then
  exit 1
fi

log "Paper-aligned output refresh completed"
